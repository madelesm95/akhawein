// Generates the static site: Arabic pages at the root, English pages under /en/.
// Usage: npm run build   (edit content in src/content/, never the generated .html files)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { transform as transformCss } from 'lightningcss';
import { transformSync as transformJs } from 'esbuild';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createContext, outputFile, pagePath, PAGES } from './lib/context.mjs';
import { documentShell } from './lib/layout.mjs';
import { site } from './content/site.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LANGS = ['ar', 'en'];

const hash = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 10);

const css = transformCss({
  filename: 'site.css',
  code: await readFile(path.join(root, 'assets/css/site.css')),
  minify: true,
  targets: { chrome: 100 << 16, safari: (15 << 16) | (4 << 8), firefox: 100 << 16 },
}).code;
const js = transformJs(await readFile(path.join(root, 'assets/js/site.js'), 'utf8'), { minify: true, target: 'es2017' }).code;
await writeFile(path.join(root, 'assets/css/site.min.css'), css);
await writeFile(path.join(root, 'assets/js/site.min.js'), js);
const verseFont = await readFile(path.join(root, 'src/data/fonts-verse.css'), 'utf8');
const fonts = {
  ar: (await readFile(path.join(root, 'src/data/fonts-ar.css'), 'utf8')) + verseFont,
  en: (await readFile(path.join(root, 'src/data/fonts-en.css'), 'utf8')) + verseFont,
};
const assets = { css: hash(css), js: hash(js), fonts };
const pages = {};
for (const key of Object.keys(PAGES)) {
  pages[key] = (await import(`./pages/${key}.mjs`)).default;
}

const banner = '<!-- Generated by src/build.mjs. Edit src/content or src/pages, then run: npm run build -->\n';
let count = 0;
for (const lang of LANGS) {
  for (const [key, render] of Object.entries(pages)) {
    const ctx = createContext(lang, key);
    const page = render(ctx);
    const out = path.join(root, outputFile(lang, key));
    await mkdir(path.dirname(out), { recursive: true });
    await writeFile(out, banner + documentShell(ctx, { ...page, assets }));
    count++;
  }
}

const notFound = (await import('./pages/404.mjs')).default;
for (const lang of LANGS) {
  const ctx = createContext(lang, '404');
  const out = path.join(root, lang === 'ar' ? '404.html' : 'en/404.html');
  await writeFile(out, banner + documentShell(ctx, { ...notFound(ctx), assets, noindex: true }));
  count++;
}

const today = new Date().toISOString().slice(0, 10);
const urls = Object.keys(PAGES).map((key) => `  <url>
    <loc>${site.origin}${pagePath('ar', key)}</loc>
    <xhtml:link rel="alternate" hreflang="ar" href="${site.origin}${pagePath('ar', key)}"/>
    <xhtml:link rel="alternate" hreflang="en" href="${site.origin}${pagePath('en', key)}"/>
    <lastmod>${today}</lastmod>
  </url>
  <url>
    <loc>${site.origin}${pagePath('en', key)}</loc>
    <xhtml:link rel="alternate" hreflang="ar" href="${site.origin}${pagePath('ar', key)}"/>
    <xhtml:link rel="alternate" hreflang="en" href="${site.origin}${pagePath('en', key)}"/>
    <lastmod>${today}</lastmod>
  </url>`).join('\n');
await writeFile(path.join(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls}
</urlset>
`);
await writeFile(path.join(root, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${site.origin}/sitemap.xml\n`);

console.log(`build: ${count} pages written (css ${assets.css}, js ${assets.js})`);
